import type { EntityPaletteItemSpec, NodeFamilySpec } from '@dialogram/shared';
/**
 * Neutral runtime options the source-model storage (and tool palette) need.
 *
 * These are the only product-shaped values core still reads directly: the VS Code settings
 * namespace to look configuration up under, and the operation-prefix string carried to the client
 * on the graph model (so the client can tell which language runtime produced the diagram). Both are
 * supplied as plain data by the consuming extension — core hardcodes NO product literals.
 */
export interface StorageRuntimeOptions {
    /** VS Code settings namespace (e.g. the `xxxLang` configuration section). */
    settingsNamespace: string;
    /** Operation-prefix identifier surfaced to the client on the graph model root args. */
    operationPrefix: string;
    /** @deprecated The platform's two Entities lists are gone; declare the rows in `entityPaletteItems`. Accepted and ignored. */
    useAlternateEntityPalette?: boolean;
    /**
     * The Entities palette: the product's rows, in its order. Plain data; the
     * platform builds each item and adds none of its own.
     */
    entityPaletteItems?: EntityPaletteItemSpec[];
    /** @deprecated The platform has no Entities entries of its own any more. Accepted and ignored. */
    platformEntityItems?: boolean;
    /**
     * The node families the product recognises — see `NodeFamilySpec`.
     * The class is derived from each annotation, so core names none.
     */
    nodeFamilies?: NodeFamilySpec[];
    /**
     * How the product navigates nested workflows (`clientBehavior.nestedNavigation`).
     * In place, a nested view's layout is the root's, stored per instance in the
     * root file's layout (see `layout-target.ts`).
     */
    nestedNavigation?: 'in-place' | 'new-editor';
    /**
     * Whether the tool palette offers anything to create. Default `true`.
     *
     * `false` empties it — the platform's Entities/Ports/Connections categories
     * AND {@link entityPaletteItems}. The palette was append-only until now: a
     * product could add an entry and never remove one, which is the wrong shape
     * for a diagram that is a projection of a source artifact. Such a diagram is
     * generated by reading a file, so a creation tool has nowhere to write; the
     * entries are inert at best, and read as a promise the diagram cannot keep.
     *
     * The suppression covers the product's own contributions deliberately. A
     * projection that has nothing to create has nothing of its own to create
     * either, and a flag that left a product's entries standing would leave the
     * palette in the exact state the flag exists to prevent.
     */
    supportsElementCreation?: boolean;
    /**
     * The layout the product's diagrams open with and Layout Diagram runs:
     * `untangled` or `free-ports`, the two layouts beside it in the Layout
     * menu (see `layout-tuned-handler.ts`). Absent, it is Layout Diagram's
     * own. Set as graph options on every loaded diagram, so the first layout
     * on open and every later Layout Diagram read them alike; a producer's own
     * graph options still win over them.
     */
    defaultLayout?: DefaultLayout;
    /**
     * What opening or closing a bus, or a node in place, does to the rest of
     * the view (toggle-port-bus-handler.ts). Absent or `relayout`, the whole
     * view is laid out again, as Layout Diagram lays it out (with
     * {@link defaultLayout}): the node changed size and which ports it has,
     * and a layout made for the old one no longer fits. `make-room` keeps
     * every node where it is and moves the ones stacked under the toggled
     * node by what it grew. Either way, undo and redo put back the layout
     * the view had.
     */
    toggleLayout?: ToggleLayout;
}

/** What a bus or node toggle does to the rest of the view. */
export type ToggleLayout = 'relayout' | 'make-room';

/** A layout a product can make its default, beside Layout Diagram's own. */
export type DefaultLayout = 'untangled' | 'free-ports';

export const STORAGE_RUNTIME_OPTIONS = Symbol('StorageRuntimeOptions');
