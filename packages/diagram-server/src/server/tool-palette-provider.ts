/**
 * Tool Palette Item Provider
 *
 * Provides tool palette items for the network diagram editor.
 * Organizes creation tools into categories: Nodes and Connections.
 */

import 'reflect-metadata';

import { injectable, inject, optional } from 'inversify';
import { 
    ToolPaletteItemProvider,
    OperationHandlerRegistry,
    CreateOperationHandler
} from '@eclipse-glsp/server';
import { 
    PaletteItem, 
    Args,
    TriggerNodeCreationAction,
    TriggerEdgeCreationAction,
    CreateNodeOperation,
    CreateEdgeOperation
} from '@eclipse-glsp/protocol';
import { WorkflowDiagramTypes } from '@dialogram/shared';
import { STORAGE_RUNTIME_OPTIONS, type StorageRuntimeOptions } from './storage-runtime-options';

/**
 * Workflow-specific tool palette item provider
 * 
 * Provides a categorized palette with:
 * - Entities (Task, Workflow)
 * - Ports (Input, Output)  
 * - Connections
 */
@injectable()
export class WorkflowToolPaletteItemProvider extends ToolPaletteItemProvider {
    
    @inject(OperationHandlerRegistry)
    protected operationHandlerRegistry!: OperationHandlerRegistry;

    @inject(STORAGE_RUNTIME_OPTIONS)
    @optional()
    protected storageOptions?: StorageRuntimeOptions;

    protected counter = 0;

    override async getItems(_args?: Args): Promise<PaletteItem[]> {
        // A diagram that is a projection of a source artifact has nothing to
        // create. Its graph is generated by reading a file, so dropping a node on
        // the canvas cannot write anything back: the tool either does nothing, or
        // — worse — appears to work and is gone on the next reload. An empty
        // palette is the honest surface for that; the flag is opt-in, so every
        // authored diagram is unaffected.
        //
        // The product's own contributions go too. A projection that has nothing
        // to create has nothing of its own to create either, and leaving those
        // standing would reproduce the exact palette the flag exists to remove.
        if (this.storageOptions?.supportsElementCreation === false) {
            return [];
        }
        // A view the producer marked read-only (`wf:readOnlyView`) still gets
        // the items: the palette asks for them once per editor, so an editor
        // that opened on such a view would keep an empty palette after
        // navigating to an editable one. The client hides them while a
        // read-only view is shown (read-only-view.ts).

        const items: PaletteItem[] = [];

        // Create Entities category: what the product declares, in its order.
        // The platform names no kind of its own: a task, an actor, a module are
        // each some product's word, and a platform that knew them would have to
        // learn every product's vocabulary.
        const entityItems: PaletteItem[] = [];
        for (const spec of this.storageOptions?.entityPaletteItems ?? []) {
            entityItems.push(this.createNodeItem(
                spec.elementTypeId,
                spec.label,
                spec.description,
                spec.icon,
                spec.args as Args | undefined
            ));
        }
        
        items.push({
            id: 'palette-entities',
            label: 'Entities',
            sortString: 'A',
            actions: [],
            children: entityItems,
            icon: 'symbol-class'
        });
        
        // Create Ports category
        const portItems: PaletteItem[] = [
            this.createNodeItem(WorkflowDiagramTypes.NODE_BOUNDARY_INPUT, 'Input Port', 'Create an input port', 'arrow-circle-down'),
            this.createNodeItem(WorkflowDiagramTypes.NODE_BOUNDARY_OUTPUT, 'Output Port', 'Create an output port', 'arrow-circle-up')
        ];
        
        items.push({
            id: 'palette-ports',
            label: 'Ports',
            sortString: 'B',
            actions: [],
            children: portItems,
            icon: 'plug'
        });
        
        // Create Connections category
        const connectionItems: PaletteItem[] = [
            this.createEdgeItem(WorkflowDiagramTypes.EDGE_CONNECTION, 'Connection', 'Create a connection between ports')
        ];
        
        items.push({
            id: 'palette-connections',
            label: 'Connections',
            sortString: 'C',
            actions: [],
            children: connectionItems,
            icon: 'arrow-right'
        });
        
        return items;
    }
    
    protected createNodeItem(
        elementTypeId: string, 
        label: string, 
        description: string,
        icon?: string,
        args?: Args
    ): PaletteItem {
        const action: TriggerNodeCreationAction = {
            kind: TriggerNodeCreationAction.KIND,
            elementTypeId,
            ...(args ? { args } : {})
        };
        
        return {
            id: `palette-item-${this.counter++}`,
            label,
            sortString: label,
            actions: [action],
            icon
        };
    }
    
    protected createEdgeItem(
        elementTypeId: string, 
        label: string,
        description: string
    ): PaletteItem {
        const action: TriggerEdgeCreationAction = {
            kind: TriggerEdgeCreationAction.KIND,
            elementTypeId
        };
        
        return {
            id: `palette-item-${this.counter++}`,
            label,
            sortString: label,
            actions: [action],
            icon: 'arrow-right'
        };
    }
}
