/**
 * Tool Palette Item Provider
 *
 * Provides tool palette items for the network diagram editor.
 * Organizes creation tools into categories: Nodes and Connections.
 */

import 'reflect-metadata';

import { injectable, inject, optional } from 'inversify';
import { 
    ToolPaletteItemProvider,
    OperationHandlerRegistry,
    CreateOperationHandler,
    ModelState
} from '@eclipse-glsp/server';
import { 
    PaletteItem, 
    Args,
    TriggerNodeCreationAction,
    TriggerEdgeCreationAction,
    CreateNodeOperation,
    CreateEdgeOperation
} from '@eclipse-glsp/protocol';
import {
    STATES_PALETTE_GROUP,
    TRANSITIONS_PALETTE_GROUP,
    VIEW_CREATE_ELEMENT_TYPE,
    WorkflowDiagramMetadata,
    WorkflowDiagramTypes,
    viewCreatesOf,
    viewEditsOf
} from '@dialogram/shared';
import { STORAGE_RUNTIME_OPTIONS, type StorageRuntimeOptions } from './storage-runtime-options';

/**
 * Workflow-specific tool palette item provider
 * 
 * Provides a categorized palette with:
 * - Entities (Task, Workflow)
 * - Ports (Input, Output)  
 * - Connections
 */
@injectable()
export class WorkflowToolPaletteItemProvider extends ToolPaletteItemProvider {
    
    @inject(OperationHandlerRegistry)
    protected operationHandlerRegistry!: OperationHandlerRegistry;

    @inject(STORAGE_RUNTIME_OPTIONS)
    @optional()
    protected storageOptions?: StorageRuntimeOptions;

    /** The view shown: the palette is asked again whenever it changes (the client's `ViewToolPalette`). */
    @inject(ModelState)
    @optional()
    protected modelState?: ModelState;

    protected counter = 0;

    override async getItems(_args?: Args): Promise<PaletteItem[]> {
        // A diagram that is a projection of a source artifact has nothing to
        // create. Its graph is generated by reading a file, so dropping a node on
        // the canvas cannot write anything back: the tool either does nothing, or
        // — worse — appears to work and is gone on the next reload. An empty
        // palette is the honest surface for that; the flag is opt-in, so every
        // authored diagram is unaffected.
        //
        // The product's own contributions go too. A projection that has nothing
        // to create has nothing of its own to create either, and leaving those
        // standing would reproduce the exact palette the flag exists to remove.
        if (this.storageOptions?.supportsElementCreation === false) {
            return [];
        }
        // A view the producer marked read-only (`wf:readOnlyView`) offers
        // what it still allows and nothing else. The client asks again each
        // time the model changes (`ViewToolPalette`), so an editor that
        // passes from such a view to an editable one gets its items back.
        const rootArgs = this.modelState?.root?.args as Record<string, unknown> | undefined;
        if (rootArgs?.[WorkflowDiagramMetadata.READ_ONLY_VIEW] === true) {
            return this.viewItems(rootArgs);
        }

        const items: PaletteItem[] = [];

        // Create Entities category: what the product declares, in its order.
        // The platform names no kind of its own: a task, an actor, a module are
        // each some product's word, and a platform that knew them would have to
        // learn every product's vocabulary.
        const entityItems: PaletteItem[] = [];
        for (const spec of this.storageOptions?.entityPaletteItems ?? []) {
            entityItems.push(this.createNodeItem(
                spec.elementTypeId,
                spec.label,
                spec.description,
                spec.icon,
                spec.args as Args | undefined
            ));
        }
        
        // A product that declares no rows offers no Entities header with nothing under it.
        if (entityItems.length > 0) {
            items.push({
                id: 'palette-entities',
                label: 'Entities',
                sortString: 'A',
                actions: [],
                children: entityItems,
                icon: 'symbol-class'
            });
        }
        
        // Create Ports category
        const portItems: PaletteItem[] = [
            this.createNodeItem(WorkflowDiagramTypes.NODE_BOUNDARY_INPUT, 'Input Port', 'Create a workflow input port', 'arrow-circle-down'),
            this.createNodeItem(WorkflowDiagramTypes.NODE_BOUNDARY_OUTPUT, 'Output Port', 'Create a workflow output port', 'arrow-circle-up')
        ];
        
        items.push({
            id: 'palette-ports',
            label: 'Ports',
            sortString: 'B',
            actions: [],
            children: portItems,
            icon: 'plug'
        });
        
        // Create Connections category
        const connectionItems: PaletteItem[] = [
            this.createEdgeItem(WorkflowDiagramTypes.EDGE_CONNECTION, 'Connection', 'Create a connection between ports')
        ];
        
        items.push({
            id: 'palette-connections',
            label: 'Connections',
            sortString: 'C',
            actions: [],
            children: connectionItems,
            icon: 'arrow-right'
        });

        return items;
    }

    /**
     * What a read-only view offers: its automaton's tools, where it allows
     * editing its states (`state`) or its transitions (`transition`), then
     * what its producer declared (`VIEW_CREATES`), each under its group, in
     * the order declared.
     */
    protected viewItems(rootArgs: Record<string, unknown>): PaletteItem[] {
        const items: PaletteItem[] = [];
        const edits = viewEditsOf(rootArgs);
        const automaton: PaletteItem[] = [];
        if (edits.includes('state')) {
            automaton.push(this.createNodeItem(WorkflowDiagramTypes.NODE_STATE, 'State', 'Place a state: drawing a transition from or to it writes it', 'circle-large-outline'));
        }
        if (edits.includes('transition')) {
            automaton.push(this.createEdgeItem(WorkflowDiagramTypes.EDGE_TRANSITION, 'Transition', 'Draw a transition from a state to a state', 'arrow-swap'));
        }
        if (automaton.length > 0) {
            items.push({
                // One group, under the id the Transition's group always had.
                id: edits.includes('transition') ? TRANSITIONS_PALETTE_GROUP : STATES_PALETTE_GROUP,
                label: 'Automaton',
                sortString: 'A',
                actions: [],
                children: automaton,
                icon: 'arrow-swap'
            });
        }
        const groups = new Map<string, PaletteItem[]>();
        for (const create of viewCreatesOf(rootArgs)) {
            const group = create.group ?? 'Create';
            const entries = groups.get(group) ?? [];
            entries.push({
                ...this.createNodeItem(VIEW_CREATE_ELEMENT_TYPE, create.label, create.description ?? create.label, create.icon ?? 'add', { create: create.id }),
                // In the order the producer declared them, not by label.
                sortString: String(entries.length).padStart(3, '0')
            });
            groups.set(group, entries);
        }
        let order = 0;
        for (const [label, children] of groups) {
            items.push({
                id: `palette-view-${++order}`,
                label,
                sortString: `B${String(order).padStart(3, '0')}`,
                actions: [],
                children,
                icon: 'add'
            });
        }
        return items;
    }
    
    protected createNodeItem(
        elementTypeId: string, 
        label: string, 
        description: string,
        icon?: string,
        args?: Args
    ): PaletteItem {
        const action: TriggerNodeCreationAction = {
            kind: TriggerNodeCreationAction.KIND,
            elementTypeId,
            ...(args ? { args } : {})
        };
        
        return {
            id: `palette-item-${this.counter++}`,
            label,
            sortString: label,
            actions: [action],
            icon
        };
    }
    
    protected createEdgeItem(
        elementTypeId: string, 
        label: string,
        description: string,
        icon = 'arrow-right'
    ): PaletteItem {
        const action: TriggerEdgeCreationAction = {
            kind: TriggerEdgeCreationAction.KIND,
            elementTypeId
        };
        
        return {
            id: `palette-item-${this.counter++}`,
            label,
            sortString: label,
            actions: [action],
            icon
        };
    }
}
